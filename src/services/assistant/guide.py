_ENTRY_FIELDS = ("title", "screen", "path", "steps", "notes")


def screen_map() -> list:
    """화면 지도 사본. 도구 결과에 그대로 실린다."""
    return [dict(item) for item in SCREEN_MAP]


def screen_map_block() -> str:
    """시스템 프롬프트에 넣는 한 줄짜리 화면 지도."""
    return "\n".join(
        f"{item['menu']}({item['path']}): {item['what']}" for item in SCREEN_MAP
    )


def _public(entry: dict) -> dict:
    """모델에게 보이는 모양. 검색용 keywords 와 id 는 빼고 준다."""
    out: dict[str, Any] = {}
    for field in _ENTRY_FIELDS:
        value = entry.get(field)
        out[field] = list(value) if isinstance(value, list) else (value or "")
    return out


def score(entry: dict, question: str) -> int:
    """물음과 항목의 겹침 점수. 클수록 가깝다.

    한국어는 형태소를 자르지 않고 부분 문자열로 본다. 현장 말투가 조사·어미로
    끝나기 때문에 낱말을 정확히 맞추려 들면 거의 안 맞는다.
    """
    text = (question or "").strip().casefold()
    if not text:
        return 0
    hit = 0
    for word in entry.get("keywords") or []:
        needle = word.casefold()
        if needle and needle in text:
            # 긴 말일수록 우연히 겹칠 일이 없으니 더 세게 본다.
            hit += 5 if len(needle) >= 4 else 3
    title = str(entry.get("title") or "").casefold()
    for chunk in title.replace(",", " ").split():
        if len(chunk) >= 2 and chunk in text:
            hit += 1
    screen = str(entry.get("screen") or "").casefold()
    if screen and screen in text:
        hit += 1
    return hit


def search(question: str, limit: int = 3) -> list:
    """물음에 가까운 안내 항목 최대 세 개. 없으면 빈 목록."""
    scored = []
    for index, entry in enumerate(ENTRIES):
        value = score(entry, question)
        if value > 0:
            scored.append((-value, index, entry))
    scored.sort()
    return [_public(entry) for _, _, entry in scored[: max(0, int(limit or 0))]]
